import { Quaternion, Vector3 } from 'three';
import { HM } from './curvature';

/**
 * Möbius (gyrovector) addition in the Poincaré ball.
 *
 * Ported from HyperEngine's HM.MobiusAdd. This one formula covers all three
 * geometries through the curvature constant K:
 *
 *   c = K(a x b)      d = 1 - K(a . b)      t = a + b
 *   a (+) b = (t*d + c x t) / (d^2 + |c|^2)
 *
 * At K = 0 it collapses exactly to a + b, which is what makes euclidean space a
 * true special case rather than an approximation.
 *
 * CodeParade's note, worth keeping: this form is much more numerically stable
 * than the one in Ungar's paper.
 *
 * NOTE: this operation is neither commutative nor associative. Composing two
 * translations produces a *rotation* (holonomy) — see {@link mobiusAddGyr}.
 */
export function mobiusAdd(a: Vector3, b: Vector3, out = new Vector3()): Vector3 {
  const K = HM.K;
  const cx = K * (a.y * b.z - a.z * b.y);
  const cy = K * (a.z * b.x - a.x * b.z);
  const cz = K * (a.x * b.y - a.y * b.x);
  const d = 1 - K * (a.x * b.x + a.y * b.y + a.z * b.z);
  const tx = a.x + b.x;
  const ty = a.y + b.y;
  const tz = a.z + b.z;
  const denom = d * d + (cx * cx + cy * cy + cz * cz);
  return out.set(
    (tx * d + (cy * tz - cz * ty)) / denom,
    (ty * d + (cz * tx - cx * tz)) / denom,
    (tz * d + (cx * ty - cy * tx)) / denom,
  );
}

/**
 * The rotation ("gyration") generated by composing two Möbius translations.
 * This is real geometric holonomy, not numerical error: walk a loop in curved
 * space and you come back facing a different direction.
 */
export function mobiusGyr(a: Vector3, b: Vector3, out = new Quaternion()): Quaternion {
  const K = HM.K;
  return out
    .set(
      K * (a.y * b.z - a.z * b.y),
      K * (a.z * b.x - a.x * b.z),
      K * (a.x * b.y - a.y * b.x),
      1 - K * (a.x * b.x + a.y * b.y + a.z * b.z),
    )
    .normalize();
}

export interface AddGyrResult {
  sum: Vector3;
  gyr: Quaternion;
}

/**
 * Combined sum + gyration. Equivalent to
 *   sum = mobiusAdd(a, b);  gyr = mobiusGyr(b, a);
 * but shares the cross product and dot product between them.
 *
 * Note the sign flip on the gyration relative to {@link mobiusGyr} — this
 * matches HyperEngine's MobiusAddGyrUnnorm, and it is the convention the
 * GyroVector composition rules are built around.
 */
export function mobiusAddGyr(a: Vector3, b: Vector3): AddGyrResult {
  const K = HM.K;
  const cx = K * (a.y * b.z - a.z * b.y);
  const cy = K * (a.z * b.x - a.x * b.z);
  const cz = K * (a.x * b.y - a.y * b.x);
  const d = 1 - K * (a.x * b.x + a.y * b.y + a.z * b.z);
  const tx = a.x + b.x;
  const ty = a.y + b.y;
  const tz = a.z + b.z;
  const denom = d * d + (cx * cx + cy * cy + cz * cz);
  return {
    sum: new Vector3(
      (tx * d + (cy * tz - cz * ty)) / denom,
      (ty * d + (cz * tx - cx * tz)) / denom,
      (tz * d + (cx * ty - cy * tx)) / denom,
    ),
    gyr: new Quaternion(-cx, -cy, -cz, d).normalize(),
  };
}

/** Squared Möbius distance. Equivalent to mobiusAdd(a, -b).lengthSq(). */
export function mobiusDistSq(a: Vector3, b: Vector3): number {
  const K = HM.K;
  const a2 = a.lengthSq();
  const b2 = b.lengthSq();
  const ab = 2 * a.dot(b);
  return (a2 - ab + b2) / (1 + K * (ab + K * a2 * b2));
}

/**
 * Ordering-only "distance" metric — cheap, monotonic in true distance, but not
 * a real distance. Useful for sorting and culling.
 */
export function poincareDist(a: Vector3, b: Vector3): number {
  const K = HM.K;
  return a.clone().sub(b).lengthSq() / ((K + a.lengthSq()) * (K + b.lengthSq()));
}
